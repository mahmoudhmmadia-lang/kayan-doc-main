// Builds the KayanOS guide in three formats from the same LaTeX sources:
//   kayanos-guide.pdf   (XeLaTeX / Tectonic)
//   kayanos-guide.docx  (rendered by docx-render.mjs; TikZ diagrams become PNGs)
//   site/               (HTML guide, Arabic + English, KayanOS web theme; Node only)
//
// Usage (from kayanos-guide/tools):  node build.mjs [--pdf-only | --docx-only | --html-only]
// Tools: set KOS_TEX to a tectonic or xelatex executable, and KOS_PDFTOPPM to
// pdftoppm (Poppler). Both default to the names on PATH.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { loadDocument } from './latex-parse.mjs';
import { imageInfo, renderDocx } from './docx-render.mjs';
import { buildHtml } from './build-html.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = path.join(ROOT, 'build');
const FIG = path.join(BUILD, 'fig');
const TEX = process.env.KOS_TEX || 'tectonic';
const PDFTOPPM = process.env.KOS_PDFTOPPM || 'pdftoppm';
const args = new Set(process.argv.slice(2));
const only = ['--pdf-only', '--docx-only', '--html-only'].find((a) => args.has(a));
const wantPdf = !only || only === '--pdf-only';
const wantDocx = !only || only === '--docx-only';
const wantHtml = !only || only === '--html-only';

function compile(texFile, outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  const isTectonic = /tectonic/i.test(path.basename(TEX));
  const run = () => execFileSync(TEX, isTectonic
    ? ['-X', 'compile', '--keep-logs', '--outdir', outDir, texFile]
    : ['-interaction=nonstopmode', '-halt-on-error', `-output-directory=${outDir}`, texFile],
  { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] });
  try {
    run();
    if (!isTectonic) { run(); run(); } // xelatex: settle TOC and references
  } catch (err) {
    const log = path.join(outDir, `${path.basename(texFile, '.tex')}.log`);
    const tail = fs.existsSync(log) ? fs.readFileSync(log, 'utf8').split('\n').filter((l) => l.startsWith('!') || /error/i.test(l)).slice(0, 8).join('\n') : '';
    throw new Error(`LaTeX failed for ${texFile}\n${tail || err.stderr?.toString().slice(-2000)}`);
  }
  return path.join(outDir, `${path.basename(texFile, '.tex')}.pdf`);
}

// Crops white margins (the diagrams are drawn on white pages).
async function trimPng(file) {
  const img = await loadImage(fs.readFileSync(file));
  const c = createCanvas(img.width, img.height);
  const g = c.getContext('2d');
  g.drawImage(img, 0, 0);
  const { data } = g.getImageData(0, 0, img.width, img.height);
  let x0 = img.width, y0 = img.height, x1 = 0, y1 = 0;
  for (let y = 0; y < img.height; y++) {
    for (let x = 0; x < img.width; x++) {
      const k = (y * img.width + x) * 4;
      if (data[k] < 245 || data[k + 1] < 245 || data[k + 2] < 245) {
        if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
      }
    }
  }
  const pad = 16;
  x0 = Math.max(0, x0 - pad); y0 = Math.max(0, y0 - pad);
  x1 = Math.min(img.width - 1, x1 + pad); y1 = Math.min(img.height - 1, y1 + pad);
  const out = createCanvas(x1 - x0 + 1, y1 - y0 + 1);
  out.getContext('2d').drawImage(c, x0, y0, out.width, out.height, 0, 0, out.width, out.height);
  fs.writeFileSync(file, out.toBuffer('image/png'));
}

// Renders every TikZ diagram to its own PNG, one diagram per page.
async function renderTikz(figures) {
  if (!figures.length) return [];
  fs.rmSync(FIG, { recursive: true, force: true });
  fs.mkdirSync(FIG, { recursive: true });
  const tmp = path.join(ROOT, '_docx-figures.tex');
  const pages = figures.map((f) => `\\begin{center}\n${f.tikz}\n\\end{center}\n\\newpage`).join('\n');
  fs.writeFileSync(tmp, `% generated by tools/build.mjs — safe to delete
\\documentclass[11pt,oneside]{report}
\\input{preamble}
\\begin{document}
\\pagestyle{empty}\\rcwatermarkfalse
${pages}
\\end{document}
`);
  try {
    const pdf = compile(tmp, FIG);
    execFileSync(PDFTOPPM, ['-r', '220', '-png', pdf, path.join(FIG, 'tikz')]);
  } finally {
    fs.rmSync(tmp, { force: true });
  }
  const pngs = fs.readdirSync(FIG).filter((f) => /^tikz-\d+\.png$/.test(f)).sort();
  const out = [];
  for (const [n, f] of pngs.entries()) {
    const file = path.join(FIG, f);
    await trimPng(file);
    const img = await loadImage(fs.readFileSync(file));
    out.push(await imageInfo(file, Math.round((img.width * 96) / 220)));
    void n;
  }
  return out;
}

function walk(blocks, fn) {
  for (const b of blocks) { fn(b); if (b.blocks) walk(b.blocks, fn); }
}

async function main() {
  fs.mkdirSync(BUILD, { recursive: true });
  if (wantHtml) {
    const pages = buildHtml(ROOT);
    console.log(`HTML -> ${pages.join(', ')}`);
  }
  if (wantPdf) {
    const pdf = compile('main.tex', BUILD);
    fs.copyFileSync(pdf, path.join(ROOT, 'kayanos-guide.pdf'));
    console.log('PDF  -> kayanos-guide.pdf');
  }
  if (wantDocx) {
    const doc = loadDocument(ROOT);
    const tikzFigures = [];
    const shots = [];
    walk(doc.blocks, (b) => {
      if (b.type === 'figure' && b.tikz) tikzFigures.push(b);
      if (b.type === 'figure' && b.image) shots.push(b);
    });
    const images = new Map();
    const rendered = await renderTikz(tikzFigures);
    if (rendered.length !== tikzFigures.length) throw new Error(`Expected ${tikzFigures.length} diagrams, got ${rendered.length}`);
    tikzFigures.forEach((b, n) => images.set(b, rendered[n]));
    for (const b of shots) {
      images.set(b, await imageInfo(path.join(ROOT, b.image), Math.round(657 * (b.imageWidth ?? 1))));
    }
    const out = path.join(ROOT, 'kayanos-guide.docx');
    await renderDocx(doc, { root: ROOT, images, outFile: out });
    console.log(`DOCX -> kayanos-guide.docx (${tikzFigures.length} diagrams, ${shots.length} screenshots)`);
  }
}

main().catch((err) => { console.error(err.message); process.exit(1); });
