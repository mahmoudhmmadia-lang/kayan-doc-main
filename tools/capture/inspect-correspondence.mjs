import fs from 'node:fs';
import assert from 'node:assert/strict';
import {open,go} from './lib.mjs';
const {browser,page}=await open({lang:'en'});
try {
 await go(page,'/official-correspondence');
 await page.getByRole('button',{name:'Not Now',exact:true}).click().catch(()=>{});
 const select=page.locator('.oc-mailbox-select');
 const original=(await select.innerText()).trim();
 await select.click();
 const options=await page.getByRole('option').allTextContents();
 const alternate=options.find(t=>t.trim()!==original);
 assert.ok(alternate,'A second position is needed to verify switching');
 await page.getByRole('option',{name:alternate,exact:true}).click();
 await page.waitForTimeout(1800);
 assert.equal((await select.innerText()).trim(),alternate.trim());
 await select.click();
 await page.getByRole('option',{name:original,exact:true}).click();
 assert.equal((await select.innerText()).trim(),original);
 await go(page,'/official-correspondence/tray');
 await page.getByRole('button',{name:/^Drafts\s*\d*$/}).click();
 await page.waitForTimeout(1800);
 assert.equal(new URL(page.url()).searchParams.get('folder'),'drafts');
 await page.getByRole('button',{name:/^Inbox\s*\d*$/}).click();
 await page.waitForTimeout(1800);
 const search=page.getByPlaceholder('Search… or @from @number @subject @to @member @position');
 await search.fill('Guide-stage1-no-match-84927');
 await page.waitForTimeout(2500);
 assert.ok((await page.locator('main').innerText()).includes('No matching'));
 await search.fill('');
 await page.waitForTimeout(2500);
 assert.ok(!(await page.locator('main').innerText()).includes('No matching'));
 await page.getByRole('button',{name:'Urgent',exact:true}).click();
 await page.waitForTimeout(1500);
 assert.ok(new URL(page.url()).searchParams.get('quick')?.includes('urgent'));
 await page.getByRole('button',{name:'Urgent',exact:true}).click();
 await page.getByRole('button',{name:'Refresh',exact:true}).click();
 console.log('PASS folders, search empty state, clear search, urgent filter, refresh');
 fs.writeFileSync(new URL('../../review/correspondence-product-verification.json',import.meta.url),JSON.stringify({environment:'test2',checks:['switch working position and restore original','folders: Inbox to Drafts and back','search with no matches','clear search restores rows','Urgent toggles URL filter','Refresh clicked'],limits:['No composition, approval, dispatch or delegation performed.']},null,2));
} finally {await browser.close();}
